from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from pathlib import Path
import json
import os
import re

BASE_DIR = Path(__file__).parent
SUBJECTS_DIR = BASE_DIR / "subjects"
META_FILE = BASE_DIR / "subjects_meta.json"

app = FastAPI(title="GTU PYQ API", version="1.0.0")

# Comma-separated list of extra allowed origins, set via env var on your host
# e.g. FRONTEND_ORIGIN=https://gtu-ranker.vercel.app,https://gtu-ranker-git-main.vercel.app
_extra_origins = [o.strip() for o in os.getenv("FRONTEND_ORIGIN", "").split(",") if o.strip()]

app.add_middleware(
    CORSMiddleware,
    allow_origins=_extra_origins,
    # keep localhost/127.0.0.1 (any port) working for local dev,
    # AND allow any *.vercel.app preview URL automatically
    allow_origin_regex=r"http://(localhost|127\.0\.0\.1)(:\d+)?|https://.*\.vercel\.app",
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

def load_meta() -> dict:
    """Load the optional subjects_meta.json that stores display names/blurbs."""
    if META_FILE.exists():
        with open(META_FILE, encoding="utf-8") as f:
            return json.load(f)
    return {}

def save_meta(meta: dict):
    with open(META_FILE, "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)

def derive_meta(code: str, meta: dict, subject_dir: Path) -> dict:
    """Return metadata for a subject, falling back to sensible defaults.

    Name / gtu_code resolution order:
    1. subjects_meta.json (manually set via PUT /subject/{subject}/meta)
    2. syllabus_info.json's "subject_name" / "subject_code"
       (auto-generated by the pipeline)
    3. the bare subject code, upper-cased (name only — gtu_code falls back
       to "" if it truly isn't known anywhere, so the frontend doesn't
       mistake a placeholder for a real GTU code)
    """
    saved = meta.get(code, {})

    default_name = code.upper()
    default_gtu_code = ""
    syllabus_path = subject_dir / "syllabus_info.json"
    if syllabus_path.exists():
        try:
            with open(syllabus_path, encoding="utf-8") as f:
                syllabus_info = json.load(f)
            default_name = syllabus_info.get("subject_name", default_name)
            default_gtu_code = syllabus_info.get("subject_code", default_gtu_code)
        except (json.JSONDecodeError, OSError):
            pass

    return {
        "code": code,
        "name": saved.get("name", default_name),
        "short": saved.get("short", code.upper()),
        "gtu_code": saved.get("gtu_code", default_gtu_code),
        "blurb": saved.get("blurb", ""),
    }

@app.get("/")
def home():
    return {"message": "GTU PYQ API", "version": "1.0.0"}

@app.get("/subjects")
def list_subjects():
    """
    List all subjects that have both topic_cards.json and website_data.json.
    Returns full metadata (name, short, blurb) so the frontend needs no
    hardcoded subject list.
    """
    meta = load_meta()
    available = []
    for subject_dir in sorted(SUBJECTS_DIR.iterdir()):
        if not subject_dir.is_dir():
            continue
        has_topics  = (subject_dir / "topic_cards.json").exists()
        has_website = (subject_dir / "website_data.json").exists()
        if has_topics and has_website:
            available.append(derive_meta(subject_dir.name, meta, subject_dir))
    return {"subjects": [s["code"] for s in available], "subjects_meta": available}

@app.get("/subject/{subject}")
def get_subject(subject: str):
    subject_dir = SUBJECTS_DIR / subject
    if not subject_dir.exists():
        raise HTTPException(status_code=404, detail=f"Subject '{subject}' not found")

    topic_cards_path  = subject_dir / "topic_cards.json"
    website_data_path = subject_dir / "website_data.json"

    if not topic_cards_path.exists():
        raise HTTPException(status_code=404, detail=f"No topic data for '{subject}' yet")
    if not website_data_path.exists():
        raise HTTPException(status_code=404, detail=f"No unit data for '{subject}' yet")

    with open(topic_cards_path,  encoding="utf-8") as f:
        topic_data = json.load(f)
    with open(website_data_path, encoding="utf-8") as f:
        unit_data  = json.load(f)
    with open(subject_dir / "syllabus_info.json", "r", encoding="utf-8") as f:
        syllabus_info = json.load(f)

    return {"topics": topic_data, "unit_questions": unit_data, "syllabus": syllabus_info}

@app.get("/subject/{subject}/papers")
def get_papers(subject: str):
    papers_dir = SUBJECTS_DIR / subject / "papers"
    if not papers_dir.exists():
        raise HTTPException(status_code=404, detail=f"No papers found for '{subject}'")

    papers = []
    for file in papers_dir.glob("*.pdf"):
        name    = file.stem
        session = "Summer" if name.startswith("S") else "Winter"
        year    = name[1:]
        papers.append({"label": f"{session} {year}", "file": file.name,
                        "session": session, "year": year})

    papers.sort(
        key=lambda x: (int(x["year"]) if x["year"].isdigit() else 0,
                        1 if x["session"] == "Winter" else 0),
        reverse=True,
    )
    return papers

@app.get("/subject/{subject}/paper/{filename}")
def get_paper_file(subject: str, filename: str):
    if not filename.endswith(".pdf") or "/" in filename or "\\" in filename or ".." in filename:
        raise HTTPException(status_code=400, detail="Invalid filename")
    paper_path = SUBJECTS_DIR / subject / "papers" / filename
    if not paper_path.exists():
        raise HTTPException(status_code=404, detail=f"Paper '{filename}' not found")
    return FileResponse(path=paper_path, media_type="application/pdf", filename=filename)

@app.put("/subject/{subject}/meta")
def update_subject_meta(subject: str, name: str = "", short: str = "", gtu_code: str = "", blurb: str = ""):
    """
    Optional endpoint: update display name/short/gtu_code/blurb for a subject.
    Call this once after adding a new subject to set its display info.
    """
    meta = load_meta()
    meta[subject] = {"name": name or subject.upper(),
                     "short": short or subject.upper(),
                     "gtu_code": gtu_code,
                     "blurb": blurb}
    save_meta(meta)
    return {"ok": True, "subject": subject, "meta": meta[subject]}

@app.get("/subject/{subject}/syllabus")
def get_syllabus(subject: str):

    subject_dir = SUBJECTS_DIR / subject

    with open(subject_dir / "syllabus_info.json", "r", encoding="utf-8") as f:
        syllabus = json.load(f)

    pdf_path = subject_dir / syllabus["syllabus_pdf"]

    if not pdf_path.exists():
        raise HTTPException(
            status_code=404,
            detail="Syllabus PDF not found"
        )

    return FileResponse(pdf_path)